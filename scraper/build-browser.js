#!/usr/bin/env node
// Concatenates lib/common.js + an adapter into one self-contained script per shop that runs
// as-is inside that shop's tab in Benji's Chrome (javascript_tool). The caller defines
// DEALS_TOKEN before the script; the script returns a one-line summary.
//   node build-browser.js      → browser/gant.js browser/adidas.js browser/ksp.js

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const strip = (src) => src.replace(/^export\s*\{[^}]*\};?\s*$/gm, "").replace(/^import .*$/gm, "");
const common = strip(readFileSync(new URL("./lib/common.js", import.meta.url), "utf8"));

const SHOPS = {
  gant:   { file: "adapters/woo.js",    call: `wooFetchDeals("gant", C, log)` },
  adidas: { file: "adapters/adidas.js", call: `adidasFetchDeals(C, log)` },
  ksp:    { file: "adapters/ksp.js",    call: `kspFetchDeals(C, log)` },
};

mkdirSync(new URL("./browser/", import.meta.url), { recursive: true });
for (const [shop, { file, call }] of Object.entries(SHOPS)) {
  const adapter = strip(readFileSync(new URL("./" + file, import.meta.url), "utf8"));
  const out = `// GENERATED by scraper/build-browser.js — do not edit. Runs in a ${shop} tab in Chrome.
// Usage (javascript_tool): const DEALS_TOKEN = "…"; <this file>   → returns at once; then poll
//   window.__DEALS_LAST ? window.__DEALS_LAST.summary : "running: " + window.__DEALS_LOG.slice(-1)
window.__DEALS_LAST = null; window.__DEALS_LOG = [];
window.__DEALS_RUN = (async () => {
${common}
${adapter}
const C = { ME, BRANDS, brandOf, kindOf, techMatch, mySize, sizeFits, score, qualify, sleep, getJson, getText, stripHtml, ingest, NOT_MEN };
const INGEST_URL = "https://gsyrqhoutpshtbzastyq.supabase.co/functions/v1/deals-ingest";
const lines = window.__DEALS_LOG; const log = (s) => lines.push(s);
const t0 = Date.now();
let result = null, failure = null;
try { result = await ${call}; } catch (e) { failure = e; }
const token = typeof DEALS_TOKEN === "string" ? DEALS_TOKEN : (window.__DEALS_TOKEN || "");
let run_id = null, ingestErr = null;
if (token) {
  try { run_id = await ingest({ url: INGEST_URL, token, shop: "${shop}", runner: "mac", items: result?.items ?? [], seen: result?.seen ?? 0, error: failure ? String(failure.message || failure) : null }); }
  catch (e) { ingestErr = String(e.message || e); }
}
const summary = \`${shop}: \${failure ? "FAILED " + String(failure.message || failure) : "seen " + result.seen + ", kept " + result.items.length}; \${token ? (ingestErr ? "ingest failed: " + ingestErr : "ingested as run " + run_id) : "no token, nothing sent"}; \${((Date.now() - t0) / 1000).toFixed(0)}s\`;
window.__DEALS_LAST = { shop: "${shop}", summary, result, failure: failure && String(failure), run_id, ingestErr };
return summary;
})();
"${shop}: started — poll window.__DEALS_LAST (null while running), window.__DEALS_LOG for progress";
`;
  writeFileSync(new URL(`./browser/${shop}.js`, import.meta.url), out);
  console.log(`browser/${shop}.js ${out.length} bytes`);
}
